    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String position = jTextField2.getText().trim();
        String s1 = jTextField3.getText().trim();
        String s2 = jTextField4.getText().trim();
        
        Department dep = departments.get(jComboBox1.getSelectedIndex());
        EmployeeType type = "Full-Time".equals(jComboBox2.getSelectedItem()) ? EmployeeType.FULL_TIME : EmployeeType.PART_TIME;
        boolean typeChanged = type != original.getType();
        
        if(!Validator.isNotEmpty(position))
            position = original.getPosition();
        
        double a , b;
        if(typeChanged){
            if(!Validator.isNotEmpty(s1) || !Validator.isNotEmpty(s2)){
                showError("You changed the employee type, so please enter both salary values.");
                return;
            }
            a = 0;
            b = 0;
        } else{
            double oldA , oldB;
            if(original.getType() == EmployeeType.FULL_TIME){
                FullTimeEmployee ft = (FullTimeEmployee) original;
                oldA = ft.getBasicSalary();
                oldB = ft.getBonus();
            } else{
                PartTimeEmployee pt = (PartTimeEmployee) original;
                oldA = pt.getHourlyRate();
                oldB = pt.getHoursWorked();
            }
            a = oldA;
            b = oldB;
        }
        
        if(Validator.isNotEmpty(s1)){
            if(!Validator.isNonNegativeNumber(s1)){
                showError(jLabel13.getText() + " must be a non-negative number.");
                return;
            }
            a = Double.parseDouble(s1);
        }
        if(Validator.isNotEmpty(s2)){
            if(!Validator.isNonNegativeNumber(s2)){
                showError(jLabel14.getText() + " must be a non-negative number.");
                return;
            }
            b = Double.parseDouble(s2);
        }
        
        String error = manager.updateEmployee(original.getId(),  position, dep, type, a, b);
    if (error != null) {
        showError(error);
        return;
    }

    JOptionPane.showMessageDialog(this, "Employee updated successfully!");
    if (onUpdated != null) {
        onUpdated.run();
    }
    dispose();
        
        
    }//GEN-LAST:event_jButton1ActionPerformed


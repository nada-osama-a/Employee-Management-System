    private void setupCombos() {
        jComboBox1.removeAllItems();
        for (Department d : departments) {
            jComboBox1.addItem(d.getDepartmentName());
        }

        jComboBox2.removeAllItems();
        jComboBox2.addItem("Full-Time");
        jComboBox2.addItem("Part-Time");

        jComboBox2.addActionListener(e -> {
            if (!loading) {
                updateSalaryLabels();
                jTextField3.setText("");
                jTextField4.setText("");
            }
        });
    }

    private void loadEmployeeData() {
        loading = true;

        jLabel3.setText(String.valueOf(original.getId()));
        jLabel8.setText(original.getName());
        jTextField2.setText(original.getPosition());

        for (int i = 0; i < departments.size(); i++) { // finds the employee's department and selects it in the combobox
            if (departments.get(i).getDepartmentId() == original.getDepartment().getDepartmentId()) {
                jComboBox1.setSelectedIndex(i);
                break;
            }
        }

        if (original.getType() == EmployeeType.FULL_TIME) {
            FullTimeEmployee ft = (FullTimeEmployee) original;
            jComboBox2.setSelectedItem("Full-Time");
            updateSalaryLabels();
            jTextField3.setText(String.valueOf(ft.getBasicSalary()));
            jTextField4.setText(String.valueOf(ft.getBonus()));

        } else {
            PartTimeEmployee pt = (PartTimeEmployee) original;
            jComboBox2.setSelectedItem("Part-Time");
            updateSalaryLabels();
            jTextField3.setText(String.valueOf(pt.getHourlyRate()));
            jTextField4.setText(String.valueOf(pt.getHoursWorked()));
        }
        
        loading = false;
    }
    
    private void updateSalaryLabels(){
        if("Full-Time".equals(jComboBox2.getSelectedItem())){
            jLabel13.setText("Basic Salary");
            jLabel14.setText("Bonus");
        } else{
            jLabel13.setText("Hourly Rate");
            jLabel14.setText("Hours Worked");
            
        }
    }
    
    private void showError(String msg) {
    JOptionPane.showMessageDialog(this, msg, "Invalid Input", JOptionPane.ERROR_MESSAGE);
}

